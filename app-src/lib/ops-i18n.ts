export const O: Record<Lang, OpsStrings> = { en, ta, hi };

/** Local date and time of an instant in India, in the customer's language. */
export const LOCALES: Record<Lang, string> = { en: "en-IN", ta: "ta-IN", hi: "hi-IN" };
export const fmtTime = (lang: Lang, iso: string) => new Date(iso).toLocaleTimeString(LOCALES[lang], { hour: "numeric", minute: "2-digit", timeZone: "Asia/Kolkata" });
export const fmtDay = (lang: Lang, iso: string) => new Date(iso).toLocaleDateString(LOCALES[lang], { weekday: "short", day: "numeric", month: "short", timeZone: "Asia/Kolkata" });
export const fmtDayTime = (lang: Lang, iso: string) => `${fmtDay(lang, iso)}, ${fmtTime(lang, iso)}`;
/** Minutes after midnight -> "10:30 am" in the customer's language. */
export const fmtMinutes = (lang: Lang, m: number) => fmtTime(lang, new Date(Date.UTC(2024, 0, 1, 0, 0) + (m - 330) * 60_000).toISOString());
